"""AI-generated image check for citizen reports.

Two signals, combined conservatively so real photos are almost never blocked:
  1. Metadata: generator tags that image tools write (Stable Diffusion parameters, Midjourney, DALL-E, Firefly, C2PA
     content credentials that say 'trainedAlgorithmicMedia'). Strong evidence on its own.
  2. A free open model (umm-maybe/AI-image-detector, runs on CPU) that scores 'artificial' vs 'human'. It is only trusted
     at a high score because it makes mistakes (one of our 12 real road photos scored 0.87), so the block threshold is 0.93.
Only still photos are checked. Videos are not."""
import io
import os
import re
import threading

AI_BLOCK = float(os.getenv("RD_AI_BLOCK", "0.93"))
AI_WARN = float(os.getenv("RD_AI_WARN", "0.75"))
MODEL_ID = os.getenv("RD_AI_DETECTOR", "umm-maybe/AI-image-detector")
_lock = threading.Lock()
_pipe = None
_err = None

TAGS = re.compile(rb"(stable diffusion|steps: \d+, sampler|sdxl|midjourney|dall[- ]?e|firefly|trainedalgorithmicmedia|"
                  rb"made with ai|generated by ai|ai generated|imagen|gemini|ideogram|leonardo\.ai|nightcafe|playground ai)", re.I)


def metadata_hit(data: bytes):
    head = data[:200_000]
    m = TAGS.search(head)
    return m.group(0).decode("latin-1") if m else None


def _model():
    global _pipe, _err
    with _lock:
        if _pipe is None and _err is None:
            try:
                from transformers import pipeline
                _pipe = pipeline("image-classification", model=MODEL_ID, device=-1)
            except Exception as e:  # missing weights or no internet: skip the model check, keep the metadata check
                _err = str(e)[:120]
                print(f"[aigen] detector unavailable: {_err}")
    return _pipe


def score(data: bytes):
    """Probability (0..1) that the photo is AI generated, or None when the model is unavailable."""
    p = _model()
    if p is None:
        return None
    try:
        from PIL import Image
        img = Image.open(io.BytesIO(data)).convert("RGB")
        img.thumbnail((768, 768))
        out = p(img)
        for r in out:
            if "artificial" in r["label"].lower() or "ai" == r["label"].lower():
                return float(r["score"])
        return 1.0 - float(out[0]["score"]) if "human" in out[0]["label"].lower() else None
    except Exception as e:
        print("[aigen] score failed:", repr(e))
        return None


def check(data: bytes):
    """-> {'ai': bool, 'score': float|None, 'reason': str|None, 'signal': 'metadata'|'model'|None}"""
    tag = metadata_hit(data)
    if tag:
        return {"ai": True, "score": 1.0, "signal": "metadata", "reason": f"The photo file says it was made by an AI image tool ({tag.strip()[:30]})."}
    sc = score(data)
    if sc is not None and sc >= AI_BLOCK:
        return {"ai": True, "score": round(sc, 3), "signal": "model", "reason": f"This photo looks AI generated (confidence {sc:.0%})."}
    return {"ai": False, "score": None if sc is None else round(sc, 3), "signal": None, "reason": None}
